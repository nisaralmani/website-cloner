#!/usr/bin/env node

/**
 * Deploy Bybelt Shopify app backend (Docker :3005) proxied via chat.bybelt.com nginx.
 * Usage: node scripts/deploy-shopify-chat-vps.mjs
 */

import { execSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { installChatNginxSite } from "./lib/nginx-chat-site.mjs";
import { resolveInternalSecret } from "./lib/internal-secret.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const appRoot = path.join(root, "shopify-app", "chat");
const appDir = "shopify-chat";
const publicUrl = "https://chat.bybelt.com";

function loadEnvFile(filePath) {
  if (!existsSync(filePath)) return {};
  const vars = {};
  for (const line of readFileSync(filePath, "utf8").split(/\r?\n/)) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    vars[trimmed.slice(0, eq).trim()] = trimmed.slice(eq + 1).trim();
  }
  return vars;
}

function loadEnvVps() {
  const envPath = path.join(root, ".env.vps");
  if (!existsSync(envPath)) {
    throw new Error("Missing .env.vps — add VPS connection details first.");
  }
  return loadEnvFile(envPath);
}

function sh(cmd, opts = {}) {
  console.log(`\n$ ${cmd}`);
  execSync(cmd, { stdio: "inherit", cwd: opts.cwd ?? root, ...opts });
}

function ssh(vps, remoteCmd) {
  const key = vps.VPS_SSH_KEY_PATH.replace(/\\/g, "/");
  const target = `${vps.VPS_USER}@${vps.VPS_IP}`;
  sh(
    `ssh -i "${key}" -o BatchMode=yes -o StrictHostKeyChecking=accept-new ${target} "${remoteCmd.replace(/"/g, '\\"')}"`,
  );
}

function scp(vps, local, remote) {
  const key = vps.VPS_SSH_KEY_PATH.replace(/\\/g, "/");
  const target = `${vps.VPS_USER}@${vps.VPS_IP}`;
  sh(`scp -i "${key}" -o BatchMode=yes "${local}" ${target}:${remote}`);
}

function main() {
  const vps = loadEnvVps();
  const localEnv = loadEnvFile(path.join(appRoot, ".env"));
  const existingProdEnv = loadEnvFile(path.join(appRoot, ".env.production"));
  const remoteBase = `${vps.VPS_REMOTE_WWW_DIR}/${appDir}`;
  const remoteWww = vps.VPS_REMOTE_WWW_DIR;
  const tarball = path.join(root, "deploy-shopify-chat.tar.gz");

  const apiKey = localEnv.SHOPIFY_API_KEY;
  const apiSecret = localEnv.SHOPIFY_API_SECRET;
  const scopes =
    localEnv.SCOPES ??
    "read_customers,read_orders,read_products,read_content,read_themes,read_fulfillments";

  if (!apiKey || !apiSecret) {
    throw new Error("Missing SHOPIFY_API_KEY or SHOPIFY_API_SECRET in shopify-app/chat/.env");
  }

  console.log(`Deploying Shopify app backend → ${publicUrl} (${remoteBase}, internal :3005)`);

  const internalSecret = resolveInternalSecret([vps, localEnv, existingProdEnv], {
    required: true,
  });

  const prodEnv = `# Generated by scripts/deploy-shopify-chat-vps.mjs
NODE_ENV=production
SHOPIFY_API_KEY=${apiKey}
SHOPIFY_API_SECRET=${apiSecret}
SCOPES=${scopes}
SHOPIFY_APP_URL=${publicUrl}
BYBELT_CHAT_ORIGIN=${localEnv.BYBELT_CHAT_ORIGIN ?? "https://chat.bybelt.com"}
BYBELT_INBOX_URL=${localEnv.BYBELT_INBOX_URL ?? "https://chat.bybelt.com"}
BYBELT_INTERNAL_SECRET=${internalSecret}
BYBELT_MAIN_INTERNAL_URL=http://bybelt-chat:3000
HOSTNAME=0.0.0.0
PORT=3000
`;
  writeFileSync(path.join(appRoot, ".env.production"), prodEnv);

  console.log("Creating deployment archive…");
  if (existsSync(tarball)) {
    execSync(`del /f /q "${tarball}"`, { stdio: "ignore", shell: true });
  }

  sh(
    `tar --exclude=node_modules --exclude=.git --exclude=build --exclude=.shopify --exclude=prisma/dev.sqlite --exclude=deploy-shopify-chat.tar.gz -czf deploy-shopify-chat.tar.gz -C shopify-app chat`,
    { shell: true },
  );

  ssh(vps, `mkdir -p ${remoteBase}/prisma ${remoteWww}/deploy/nginx`);
  scp(vps, tarball, `${remoteBase}/deploy-shopify-chat.tar.gz`);
  scp(
    vps,
    path.join(root, "deploy", "nginx", "chat.bybelt.com.conf"),
    `${remoteWww}/deploy/nginx/chat.bybelt.com.conf`,
  );

  ssh(
    vps,
    `cd ${remoteBase} && tar -xzf deploy-shopify-chat.tar.gz --strip-components=1 && rm deploy-shopify-chat.tar.gz && docker compose -f docker-compose.prod.yml up -d --build`,
  );

  console.log("\nUpdating chat.bybelt.com nginx (Shopify routes → :3005)…");
  installChatNginxSite(
    vps,
    `${remoteWww}/deploy/nginx/chat.bybelt.com.conf`,
    ssh,
  );

  console.log("\nDeployed successfully:");
  console.log(`  Plugin URL: ${publicUrl}/initiate/plugin/shopify`);
  console.log("\nNext: push URLs to Shopify Partners:");
  console.log("  cd shopify-app/chat && shopify app deploy --allow-updates");
}

main();
